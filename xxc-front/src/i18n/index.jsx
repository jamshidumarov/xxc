const LanguageContext = createContext()

export function LanguageProvider({ children }) {
  const [lang, setLang] = useState(() => {
    const saved = localStorage.getItem('xxc_lang')
    return translations[saved] ? saved : 'uz'
  })

  const t = translations[lang]

  useEffect(() => {
    document.documentElement.lang = lang
    document.querySelector('meta[name="description"]')?.setAttribute('content', t.meta.description)
  }, [lang, t])

  const changeLang = (l) => {
    setLang(l)
    localStorage.setItem('xxc_lang', l)
  }

  // Returns the right language field from an API object.
  // field(item, 'name')  → item.nameUz / item.nameRu / item.nameEn
  // field(item, 'title') → item.titleUz / item.titleRu / item.titleEn
  const field = (obj, name) => {
    if (!obj) return ''
    const suffix = lang === 'ru' ? 'Ru' : lang === 'en' ? 'En' : 'Uz'
    return obj[name + suffix] || obj[name + 'Uz'] || ''
  }

  return (
    <LanguageContext.Provider value={{ lang, t, changeLang, field }}>
      {children}
    </LanguageContext.Provider>
  )
}

export const useLang = () => useContext(LanguageContext)
